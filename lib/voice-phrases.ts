export type PhraseName = keyof typeof BASE;
export type PhraseId = `${PhraseName}.${Gender}`;

export const FILLERS: PhraseName[] = ["filler1", "filler2", "filler3"];

export function phraseId(name: PhraseName, gender: Gender): PhraseId {
  return `${name}.${gender}`;
}

export function isPhraseId(value: unknown): value is PhraseId {
  if (typeof value !== "string") return false;
  const [name, gender] = value.split(".");
  return Object.hasOwn(BASE, name) && (gender === "m" || gender === "f");
}

export function phraseText(id: PhraseId): string {
  const [name, gender] = id.split(".") as [PhraseName, Gender];
  return BASE[name][gender];
}
